export function getMat(key: string): MatSpec {
  return MATERIALS.find((m) => m.key === key) ?? MATERIALS[0];
}

/** Allowable stress at temperature (MPa), linear interpolation between table points. */
export function allowableAt(key: string, tC: number): number {
  const m = getMat(key);
  return interp(m.allowable, tC);
}

export function matPrice(key: string, overrides?: Record<string, number>): number {
  const m = getMat(key);
  return overrides?.[key] ?? m.pricePerKg;
}

